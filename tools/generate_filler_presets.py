def main() -> int:
    factory = ROOT / "presets" / "factory"
    if not factory.is_dir():
        print(f"factory dir not found: {factory}", file=sys.stderr)
        return 1
    written = 0
    for corner, cfg in CORNERS.items():
        out_dir = factory / cfg["dir"]
        out_dir.mkdir(parents=True, exist_ok=True)
        template_fn = TEMPLATES[corner]
        for slot in cfg["slots"]:
            rng = random.Random(slot)  # deterministic seed
            preset = template_fn(slot, rng)
            path = out_dir / f"{slot:03d}_{corner}_filler_{slot}.sfs"
            with open(path, "w") as f:
                json.dump(preset, f, indent=2)
                f.write("\n")
            written += 1
    print(f"Wrote {written} filler presets.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
