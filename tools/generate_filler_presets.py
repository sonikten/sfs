def _round(x: float, digits: int = 4) -> float:
    return round(x, digits)


def _vary(rng: random.Random, base: float, lo: float, hi: float, jitter: float) -> float:
    """Return base + uniform(-jitter, jitter), clamped to [lo, hi]."""
    return _round(max(lo, min(hi, base + (rng.random() * 2.0 - 1.0) * jitter)))


