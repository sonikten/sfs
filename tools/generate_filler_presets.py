#!/usr/bin/env python3
"""
tools/generate_filler_presets.py — Phase 4 §A6b filler-preset generator.

Doc 09 §4 mandates 128 named factory presets but explicitly permits
filler entries: "Rows marked _(Phase 4)_ are placeholders that Phase 4
sound design will fill — the table specifies the count and category but
not the final names."

This script reads one named template per corner, varies the macros
inside corner-safe bands using a deterministic seeded PRNG, and writes
the unfilled slot IDs from Doc 09 §4. Output is committed to the repo;
the script is run once per palette regeneration (rare).

Usage:
    tools/generate_filler_presets.py

Determinism:
    The PRNG is seeded with the slot ID, so re-running the script
    produces byte-identical output. The generated presets feed the
    cross-platform hash test like any other factory preset.

Authoring policy:
    - drone   slots 6-32:   small variations of Slow Glacier; coherence
                            stays at 1.0, excitation at 0.0 to keep cv
                            comfortably under 0.05.
    - organic slots 37-64:  variations of Forest Breath; migration ≥ 0.4
                            and LFO routing on coherence/excitation
                            preserve the > 50 Hz centroid stddev.
    - pitched slots 69-88:  variations of Glass Pad; coherence locked at
                            1.0, migration at 0.0 (pitched threshold
                            requires both).
    - glitch  slots 93-104: variations of Init Glitch; S&H LFOs on
                            DENSITY/EXCITATION at depth ≥ 0.4 produce
                            ≥ 5 onsets reliably.
    - hybrid  slots 110-120: blends with no contract tag (the gate
                            doesn't measure them).

Each filler is named `<Category> Filler N` so the chooser surface stays
readable; users renaming via Save As is the authoring path.
"""
